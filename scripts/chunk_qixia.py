def build_qixia_chunks() -> list[Chunk]:
    on_disk = {p.stem for p in config.RAW_NOTES_DIR.glob("b460_*.json")}
    uncovered = on_disk - set(SPECS)
    if uncovered:
        print(f"warn: b460 notes without chunk specs: {sorted(uncovered)}")
    chunks: list[Chunk] = []
    for nid, specs in SPECS.items():
        note_file = config.RAW_NOTES_DIR / f"{nid}.json"
        if not note_file.exists():
            print(f"warn: {nid} not on disk, skipped")
            continue
        note = json.loads(note_file.read_text(encoding="utf-8"))
        cover = note["images"][0] if note.get("images") else (
            note["image_urls"][0] if note.get("image_urls") else "")
        for i, (loc, typ, content, tags, locs, acts, th, food, tips,
                conf) in enumerate(specs):
            chunks.append(Chunk(
                chunk_id=f"ck_{nid}_{i}",
                source_note_id=nid,
                location=loc,
                type=typ,
                content=content,
                tags=list(tags),
                structured_data={
                    "locations": list(locs),
                    "activities": list(acts),
                    "time_hint": th,
                    "food": list(food),
                    "tips": list(tips),
                },
                source_ref={
                    "note_title": note["title"],
                    "note_url": note["url"],
                    "image": cover,
                },
                confidence=conf,
                created_at=CREATED_AT,
            ))
    return chunks


def main() -> None:
    new = build_qixia_chunks()

    # 语料 = mock 种子 + 既有非 b460 chunk + 新栖霞 chunk。
    # mock 是离线开发/测试种子语料（见 seed_index.py 契约），不能丢；
    # 幂等：重跑时先剔除全部 ck_b460_* 与 mock 再按序重写。
    mock = load_chunks(config.MOCK_DIR / "chunks.json")
    mock_ids = {c.chunk_id for c in mock}
    existing = []
    if config.CHUNKS_FILE.exists():
        existing = [c for c in load_chunks(config.CHUNKS_FILE)
                    if not c.chunk_id.startswith("ck_b460_")
                    and c.chunk_id not in mock_ids]
    chunks = mock + existing + new

    save_chunks(chunks, config.CHUNKS_FILE)
    graph = KnowledgeGraph.build(chunks)
    graph.save(config.GRAPH_FILE)
    provider = make_default_provider()
    index = build_index(chunks, provider)
    save_index(index, config.INDEX_DIR)

    print(f"new qixia chunks: {len(new)} (from {len(SPECS)} notes)")
    print(f"total chunks: {len(chunks)} -> {config.CHUNKS_FILE}")
    print(f"graph locations: {len(graph.locations)} -> {config.GRAPH_FILE}")
    print(f"index vectors: {len(index.vectors)} -> {config.INDEX_DIR}")
    print(f"provider: {type(provider).__name__} (dim={provider.dim})")


if __name__ == "__main__":
    main()
